#!/usr/bin/env python
"""Phase 7: read-only fingerprint of the KB data in a database, for diffing local vs hosted.

DB    : DATABASE_URL environment variable only (never argv). Hosts other than
        localhost / 127.0.0.1 / ::1 are refused unless --allow-remote is given, and a
        remote URL must also set sslmode=verify-full (libpq's require does not verify
        the server).
Config: config/embedding/article-v1.json, read with embed_kb.load_config

Run:  .venv/Scripts/python scripts/db_fingerprint.py [--per-article] [--settings] [--allow-remote]

Rules
-----
Read only    One transaction that starts with SET TRANSACTION READ ONLY and is always
             rolled back. psycopg connects with prepare_threshold=None (transaction
             pooler safe). No query text is involved anywhere.
Rows         Articles and embeddings are ordered by source_article_id COLLATE "C".
             Embeddings are those of the config file's config_sha256 (the one the
             server searches); an article without one hashes its embedding fields as
             null. A row is every articles column except id (identity, regenerated by
             a reset), plus search_vector::text and kb_article_v1_sha256, plus the
             embedding fields (ARTICLE_FIELDS; serialization in article_row_bytes).
             The aggregate is sha256 of all row bytes in order, the per-article row
             hash is sha256 of one row's bytes.
Vectors      embedding::real[] packed as little-endian float32. The aggregate is sha256
             over "<source_article_id> <dims>\\n" + packed bytes, per embedding in order;
             the per-article vector hash is sha256 of one embedding's packed bytes.
--per-article  One line per article: "<source_article_id> <row hash> <vector hash>",
             vector hash "none" when the article has no embedding for the config.
Output       Deterministic lines, so two runs compare with a plain diff. Counts, hashes,
             config fields, versions and (--settings) server settings only: never the
             connection string, a password or any article text. On a database error
             only the exception class, SQLSTATE and constraint name are printed.
Exit codes   0 ok, 2 usage/config, 3 database error.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import struct
import sys

import embed_kb
import ingest_kb

FORMAT_VERSION = "db-fingerprint-v2"
COUNT_TABLES = ("articles", "article_embeddings", "embedding_configs")
SETTINGS = (
    "shared_preload_libraries",
    "session_preload_libraries",
    "auto_explain.log_min_duration",
    "auto_explain.log_parameter_max_length",
    "auto_explain.log_nested_statements",
    "log_min_duration_statement",
    "log_min_duration_sample",
    "log_statement_sample_rate",
    "log_transaction_sample_rate",
    "log_statement",
    "log_parameter_max_length",
    "log_parameter_max_length_on_error",
    "pgaudit.log",
    "pgaudit.log_parameter",
    "statement_timeout",
)

EXIT_OK, EXIT_USAGE, EXIT_EXTERNAL = 0, 2, 3

# One article row, in this order. Every articles column except id, plus the derived
# hashes and this config's embedding fields (all null when there is no embedding).
# Timestamps are rendered in SQL as UTC ISO 8601 with microseconds, so the session
# TimeZone cannot change them. loaded_at (load time) is deliberately not included.
UTC_ISO = "'YYYY-MM-DD\"T\"HH24:MI:SS.US\"Z\"'"
ARTICLE_FIELDS = (
    ("source_article_id", "a.source_article_id"),
    ("title", "a.title"),
    ("url", "a.url"),
    ("category", "a.category"),
    ("tags", "a.tags"),
    ("description", "a.description"),
    ("published_time", f"to_char(a.published_time at time zone 'UTC', {UTC_ISO})"),
    ("modified_time", f"to_char(a.modified_time at time zone 'UTC', {UTC_ISO})"),
    ("full_text", "a.full_text"),
    ("question", "a.question"),
    ("answer", "a.answer"),
    ("issue", "a.issue"),
    ("environment", "a.environment"),
    ("cause", "a.cause"),
    ("resolution", "a.resolution"),
    ("sections", "a.sections"),
    ("staff_only", "a.staff_only"),
    ("audience_labels", "a.audience_labels"),
    ("footer", "a.footer"),
    ("parser_version", "a.parser_version"),
    ("warnings", "a.warnings"),
    ("search_vector", "a.search_vector::text"),
    ("kb_article_v1_sha256", "kb_article_v1_sha256(a.title, a.full_text)"),
    ("source_text_sha256", "e.source_text_sha256"),
    ("input_sha256", "e.input_sha256"),
    ("input_kind", "e.input_kind"),
    ("input_tokens", "e.input_tokens"),
    ("truncated", "e.truncated"),
)
ARTICLE_ROWS_SQL = (
    f"select {', '.join(expr for _, expr in ARTICLE_FIELDS)} "
    "from articles a left join article_embeddings e "
    "on e.source_article_id = a.source_article_id and e.config_sha256 = %s "
    'order by a.source_article_id collate "C"')
VECTOR_ROWS_SQL = (
    "select source_article_id, embedding::real[] from article_embeddings "
    'where config_sha256 = %s order by source_article_id collate "C"')
CONFIG_ROWS_SQL = (
    "select config_sha256, config, model, dimensions, template_version "
    'from embedding_configs order by config_sha256 collate "C"')


# ------------------------------------------------------------------ config


def check_url(url: str | None, allow_remote: bool, environ) -> str | None:
    """Return an error message, or None if the URL may be used. Never echoes the URL."""
    problem = ingest_kb.check_database_url(url, allow_remote, environ)
    if problem:
        return problem
    if ingest_kb.check_database_url(url, False, environ) is None:
        return None  # local host
    from psycopg.conninfo import conninfo_to_dict
    if conninfo_to_dict(url).get("sslmode") != "verify-full":
        return "remote DATABASE_URL must set sslmode=verify-full"
    return None


# ------------------------------------------------------------------ hashing


def article_row_bytes(row) -> bytes:
    """Canonical bytes of one row: a JSON array of the values in ARTICLE_FIELDS order
    (position fixes the field; no names), SQL NULL as null, text[] as a JSON array in
    stored order, jsonb as decoded by psycopg and re-encoded by embed_kb.canonical_json
    (keys sorted, no spaces, non-ASCII as \\u escapes, NaN refused), then LF."""
    if len(row) != len(ARTICLE_FIELDS):
        raise ValueError("article row has the wrong number of fields")
    return embed_kb.canonical_json(list(row)) + b"\n"


def vector_bytes(values) -> bytes:
    return struct.pack(f"<{len(values)}f", *values)


# ------------------------------------------------------------------ database


def collect(conn, config_sha256: str, settings: bool) -> dict:
    """Everything the report needs. Caller owns the (read-only) transaction."""
    out = {}
    with conn.cursor() as cur:
        out["counts"] = {}
        for table in COUNT_TABLES:
            cur.execute(f"select count(*) from {table}")
            out["counts"][table] = cur.fetchone()[0]

        cur.execute(CONFIG_ROWS_SQL)
        out["configs"] = cur.fetchall()

        cur.execute(ARTICLE_ROWS_SQL, [config_sha256])
        agg, per_article, n = hashlib.sha256(), [], 0
        for row in cur:
            b = article_row_bytes(row)
            agg.update(b)
            per_article.append((row[0], hashlib.sha256(b).hexdigest()))
            n += 1
        out["articles"] = (agg.hexdigest(), n)
        out["per_article"] = per_article

        cur.execute(VECTOR_ROWS_SQL, [config_sha256])
        agg, per_vector, n = hashlib.sha256(), {}, 0
        for sid, values in cur:
            packed = vector_bytes(values)
            agg.update(f"{sid} {len(values)}\n".encode("ascii"))
            agg.update(packed)
            per_vector[sid] = hashlib.sha256(packed).hexdigest()
            n += 1
        out["vectors"] = (agg.hexdigest(), n)
        out["per_vector"] = per_vector

        cur.execute("select extversion from pg_extension where extname = 'vector'")
        got = cur.fetchone()
        out["pgvector"] = got[0] if got else None
        cur.execute("select current_setting('server_version')")
        out["server_version"] = cur.fetchone()[0]

        if settings:
            out["settings"] = read_settings(cur)
    return out


def read_settings(cur) -> list[tuple[str, str]]:
    """current_setting(name, true) per name, each under a savepoint: an unknown name is
    "unset", one this role may not read is "hidden" (and does not abort the report)."""
    import psycopg
    out = []
    for name in SETTINGS:
        cur.execute("savepoint kb_setting")
        try:
            cur.execute("select current_setting(%s, true)", [name])
            value = cur.fetchone()[0]
            out.append((name, "unset" if value is None else value))
            cur.execute("release savepoint kb_setting")
        except psycopg.errors.InsufficientPrivilege:
            cur.execute("rollback to savepoint kb_setting")
            out.append((name, "hidden"))
    cur.execute("select current_user")
    out.append(("current_user", cur.fetchone()[0]))
    return out


def run_fingerprint(url: str, config_sha256: str, settings: bool, connect=None) -> dict:
    if connect is None:
        import psycopg
        connect = psycopg.connect
    # Not "with connect(...)": that commits on success. This always rolls back.
    conn = connect(url, prepare_threshold=None)
    try:
        with conn.cursor() as cur:
            cur.execute("set transaction read only")
        return collect(conn, config_sha256, settings)
    finally:
        try:
            conn.rollback()
        finally:
            conn.close()


# ------------------------------------------------------------------ report


def render(data: dict, cfg: dict, config_sha256: str, per_article: bool) -> list[str]:
    file_bytes = embed_kb.canonical_json(cfg)
    lines = [FORMAT_VERSION]
    for table in COUNT_TABLES:
        lines.append(f"count {table} {data['counts'][table]}")
    lines.append(f"config_file sha256 {config_sha256}")
    for sha, stored, model, dims, template_version in data["configs"]:
        lines.append(f"embedding_config {sha} model {model} dimensions {dims} "
                     f"template_version {template_version}")
        same = embed_kb.canonical_json(stored) == file_bytes
        lines.append(f"embedding_config {sha} config_equals_file {str(same).lower()} "
                     f"sha256_equals_file {str(sha == config_sha256).lower()}")
    agg, n = data["articles"]
    lines.append(f"articles_sha256 {agg} rows {n} config {config_sha256}")
    agg, n = data["vectors"]
    lines.append(f"vectors_sha256 {agg} rows {n} config {config_sha256} encoding float32le")
    lines.append(f"pgvector {data['pgvector'] or 'absent'}")
    lines.append(f"server_version {data['server_version']}")
    for name, value in data.get("settings", []):
        lines.append(f"setting {name} {value}")
    if per_article:
        vectors = data["per_vector"]
        lines += [f"{sid} {h} {vectors.get(sid, 'none')}" for sid, h in data["per_article"]]
    return lines


# ------------------------------------------------------------------ main


def main(argv=None, environ=None, run_fingerprint=run_fingerprint) -> int:
    environ = os.environ if environ is None else environ
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--per-article", action="store_true",
                    help="also print one '<source_article_id> <row hash> <vector hash>' "
                         "line per article")
    ap.add_argument("--settings", action="store_true",
                    help="also print selected server settings and current_user")
    ap.add_argument("--allow-remote", action="store_true",
                    help="allow a DATABASE_URL host other than localhost (needs "
                         "sslmode=verify-full)")
    args = ap.parse_args(argv)

    url = environ.get("DATABASE_URL")
    problem = check_url(url, args.allow_remote, environ)
    if problem:
        print(f"config error: {problem}")
        return EXIT_USAGE
    try:
        cfg, config_sha256 = embed_kb.load_config(embed_kb.CONFIG_PATH)
    except embed_kb.EmbedError as exc:
        print(f"config error: {exc}")
        return EXIT_USAGE

    import psycopg
    try:
        data = run_fingerprint(url, config_sha256, args.settings)
    except psycopg.Error as exc:
        print(ingest_kb.describe_db_error(exc))
        print("rolled back")
        return EXIT_EXTERNAL
    for line in render(data, cfg, config_sha256, args.per_article):
        print(line)
    return EXIT_OK


if __name__ == "__main__":
    sys.stdout.reconfigure(errors="backslashreplace")
    sys.exit(main())
